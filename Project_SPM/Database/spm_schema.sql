-- ---------- Stored procedure ----------

CREATE OR REPLACE PROCEDURE SPGET_SPM_MASTERLIST (
  P_MASTER_TYPE   IN VARCHAR2,
  P_MACHINEID     IN VARCHAR2,
  P_SECTION       IN VARCHAR2,
  P_EQUIP_L1      IN VARCHAR2,
  CV_1 IN OUT SYS_REFCURSOR
) IS
BEGIN
  DECLARE
    ERR_MSG   VARCHAR2(200);
    ERR_CODE  VARCHAR2(100);
  BEGIN
    IF P_MASTER_TYPE = 'S' THEN
      OPEN CV_1 FOR SELECT UNIQUE(SECTION) AS SECTION FROM MST_SPM_EQUIPMENT WHERE MACHINEID = P_MACHINEID;
    ELSIF (P_MASTER_TYPE IN ('OBS','AFP')) THEN
      OPEN CV_1 FOR SELECT
                      CODEID,
                      CODEDESC FROM MST_SPM_CODES
                      WHERE MACHINEID = P_MACHINEID
                        AND CODETYPE = P_MASTER_TYPE;
    ELSIF P_MASTER_TYPE = 'EL1' THEN
      OPEN CV_1 FOR SELECT
                      UNIQUE(EQUIP_L1) AS EQUIP_L1 FROM MST_SPM_EQUIPMENT
                      WHERE MACHINEID = P_MACHINEID
                        AND SECTION = P_SECTION;
    ELSIF P_MASTER_TYPE = 'EL2' THEN
      OPEN CV_1 FOR SELECT EQUIPID_L2,
                           EQUIPDESC_L2 FROM MST_SPM_EQUIPMENT
                      WHERE MACHINEID = P_MACHINEID
                        AND SECTION = P_SECTION
                        AND EQUIP_L1 = P_EQUIP_L1;
    ELSIF P_MASTER_TYPE = 'EL2_M' THEN
      OPEN CV_1 FOR SELECT EQUIP_L2_ROLLDIA, HARDNESS, EQUIP_L2_ROLLCOAT, MAINT_PHILOSOPHY, REPLACEMENT_FREQ, EQUIP_L2_TOUCHPOINT FROM MST_SPM_EQUIPMENT
                      WHERE EQUIPID_L2 = P_EQUIP_L1; -- L2 id is passed as L1 for this branch
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      BEGIN
        ERR_MSG := DBMS_UTILITY.FORMAT_ERROR_BACKTRACE ||'-'|| SUBSTR(SQLERRM, 1, 200);
        ERR_CODE := SQLCODE;
        INSERT INTO ERRORLOG (ERROR_PROCEDURE, ERROR_LINE, ERROR_NUMBER, ERROR_MESSAGE, ERROR_TIME, ERROR_TYPE)
        VALUES
        ('SPGET_SPM_MASTERLIST', NULL, ERR_CODE, ERR_MSG, SYSDATE, 'E');
      END;
  END;
END;
/

